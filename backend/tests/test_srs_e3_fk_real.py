class RealCase(unittest.TestCase):
    def setUp(self):
        import _srs_e2_adapter as adapter

        self.adapter = adapter
        self.run = harness.PgRun(harness.requested(os.environ))
        self.run.start()
        self.addCleanup(self.run.teardown)
        scope = adapter.app_scope(self.run)
        scope.__enter__()
        self.addCleanup(scope.__exit__, None, None, None)

    # ---- schema steps (managed connection, one transaction) -------------------
    def create(self, old: bool = False):
        apply = old_schema if old else None
        self.run.track_creation(self.adapter.schema_step(apply), expected=self.adapter.expected_schema_tables())

    def upgrade(self):
        self.run.track_creation(self.adapter.schema_step(), expected=set())

    def ddl(self, *statements):
        def step(raw):
            for statement in statements:
                raw.execute(statement)
        self.run.track_creation(step, expected=set())

    # ---- app-side reads ------------------------------------------------------
    def sql(self, statement, params=()):
        from app.database import get_connection

        with get_connection() as c:
            cursor = c.execute(statement, params)
            try:
                return [dict(r) for r in cursor.fetchall()]
            except Exception:
                return []

    def fks(self):
        return self.sql(FK_SQL)

    def card_fks(self):
        return [f for f in self.fks() if "vocab_item_id" in f["columns"]]

    def catalog(self):
        nullable = self.sql("SELECT is_nullable, data_type FROM information_schema.columns WHERE table_schema = "
                            "current_schema() AND table_name = 'review_logs' AND column_name = 'vocab_item_id'")
        indexes = self.sql("SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() "
                           "AND tablename = 'review_logs' ORDER BY indexname")
        return {"fks": self.fks(), "vocab_item_id": nullable, "indexes": indexes}

    def checksums(self):
        out = {}
        for table in sorted(self.run.owned):
            out[table] = self.sql(f"SELECT count(*) AS n, md5(coalesce(string_agg(t::text, '|' ORDER BY t::text), '')) AS h "
                                  f"FROM {table} t")[0]
        return out


