def judge_overlap(box: dict) -> None:
    """Both jobs ran to the end and the second really waited FOR THE FIRST: its backend held
    a not-granted lock in this database while pg_blocking_pids() named the first's backend."""
    assert box.get("first_paused") is True, box
    assert box.get("joined") is True, box
    assert "first" in box and "second" in box, box
    assert box.get("second_blocked_by_first") is True, box
    assert box.get("second_done_while_first_held") is False, box


def judge_delete_review(box: dict, order: str, kind: str) -> None:
    """A word / deck delete overlapping a review of the same card, judged on the repository
    contract only (an HTTP 404 is a different layer and is checked separately):
    - delete first: the delete returns normally; the review then RETURNS None (card gone).
    - review first: the review returns its result; the delete then returns normally.
    Any exception -- RuntimeError, DeadlockDetected, LockNotAvailable, ... -- fails."""
    judge_overlap(box)
    delete, review = (box["first"], box["second"]) if order == "delete first" else (box["second"], box["first"])
    assert delete[0] == "ok", delete
    if kind == "word":
        assert delete[1] is True, delete
    else:
        assert isinstance(delete[1], dict) and delete[1].get("deleted_vocab_count") == 1, delete
    assert review[0] == "ok", review
    if order == "delete first":
        assert review[1] is None, review
    else:
        assert isinstance(review[1], dict) and review[1].get("card_id") is not None, review


class JudgeTests(unittest.TestCase):
    """No database: the judgment must reject anything but the repository contract and a
    proven wait on the first job."""

    def box(self, **over):
        base = {"first_paused": True, "joined": True, "second_blocked_by_first": True,
                "second_done_while_first_held": False, "first": ("ok", True), "second": ("ok", None)}
        base.update(over)
        return base

    def test_delete_first_accepts_only_a_normal_none(self):
        judge_delete_review(self.box(), "delete first", "word")
        judge_delete_review(self.box(first=("ok", {"deleted_vocab_count": 1})), "delete first", "deck")
        for name, second in {"RuntimeError": ("error", RuntimeError("unrelated")),
                             "deadlock": ("error", type("DeadlockDetected", (Exception,), {})("deadlock")),
                             "lock timeout": ("error", type("LockNotAvailable", (Exception,), {})("timeout")),
                             "a written review": ("ok", {"card_id": 1})}.items():
            with self.subTest(name), self.assertRaises(AssertionError):
                judge_delete_review(self.box(second=second), "delete first", "word")

    def test_review_first_needs_both_results(self):
        good = self.box(first=("ok", {"card_id": 1}), second=("ok", True))
        judge_delete_review(good, "review first", "word")
        for name, change in {"delete raised": {"second": ("error", RuntimeError("x"))},
                             "review raised": {"first": ("error", RuntimeError("x"))},
                             "review returned None": {"first": ("ok", None)},
                             "delete returned False": {"second": ("ok", False)}}.items():
            with self.subTest(name), self.assertRaises(AssertionError):
                judge_delete_review({**good, **change}, "review first", "word")

    def test_overlap_itself_must_be_proven(self):
        for name, change in {"no result": {"second": None}, "missing result": {"__drop__": "second"},
                             "not joined": {"joined": False}, "never paused": {"first_paused": False},
                             "waited on someone else": {"second_blocked_by_first": False},
                             "finished while the first held": {"second_done_while_first_held": True}}.items():
            with self.subTest(name), self.assertRaises((AssertionError, TypeError)):
                box = self.box()
                box.update({k: v for k, v in change.items() if k != "__drop__"})
                box.pop(change.get("__drop__", "-"), None)
                judge_delete_review(box, "delete first", "word")


def pg_checkpoint() -> None:
    """A no-op the negative control pauses at."""


class Overlap:
    """Run `first` until it is inside its transaction (paused at `pause`), start `second`,
    and PROVE the second waits for the first: the backend pid of every app connection each
    job opens is recorded (connection info, no extra query on the app connection); the
    monitor asks pg_locks / pg_blocking_pids() whether the second's backend holds a
    not-granted lock in this database and is blocked by the first's backend. Then release
    (always, in finally), join with a time limit, collect outcomes."""

    def __init__(self, case: RealCase, pause_target, pause_name: str, on_call: int = 1):
        self.case, self.target, self.name, self.on_call = case, pause_target, pause_name, on_call
        self.calls = 0
        self.entered, self.release = threading.Event(), threading.Event()
        self.box: dict = {}
        self.pids: dict[str, list[int]] = {}

    def blocked_by(self, waiter: str, holder: str) -> dict:
        """Through the harness's own guarded connection with the target check only -- not an
        app connection, which reads the run marker a managed schema step may hold
        exclusively (the monitor would queue behind what it observes)."""
        run = self.case.run
        waiter_pids, holder_pids = self.pids.get(waiter, []), set(self.pids.get(holder, []))
        if not waiter_pids or not holder_pids:
            return {"blocked": False, "waits": []}
        with run._connection() as connection:
            try:
                run._check_target(connection)
                rows = run._rows(connection, """
                    SELECT l.locktype, COALESCE(l.relation::regclass::text, ''), l.mode, pg_blocking_pids(l.pid)
                    FROM pg_locks l
                    WHERE l.pid = %s AND NOT l.granted
                      AND (l.database IS NULL OR l.database = (SELECT oid FROM pg_database WHERE datname = current_database()))
                    """, (waiter_pids[-1],))
            finally:
                connection.rollback()
        waits = [{"locktype": r[0], "relation": r[1], "mode": r[2], "blockers": list(r[3] or [])} for r in rows]
        return {"blocked": any(holder_pids & set(w["blockers"]) for w in waits), "waits": waits}

    def run(self, first, second):
        import _srs_e2_adapter as adapter

        real = getattr(self.target, self.name)
        real_connect = adapter._GuardedPsycopg.connect

        def recording(shim, url, **kwargs):
            connection = real_connect(shim, url, **kwargs)
            self.pids.setdefault(threading.current_thread().name, []).append(connection.info.backend_pid)
            return connection

        def paused(*args, **kwargs):
            result = real(*args, **kwargs)
            if threading.current_thread().name == "first":
                self.calls += 1
                if self.calls == self.on_call and not self.entered.is_set():
                    self.entered.set()
                    if not self.release.wait(WAIT):
                        raise TimeoutError("first was never released")
            return result

        def job(name, fn):
            try:
                self.box[name] = ("ok", fn())
            except BaseException as error:  # noqa: BLE001
                self.box[name] = ("error", error)

        threads = []
        with mock.patch.object(self.target, self.name, paused), \
                mock.patch.object(adapter._GuardedPsycopg, "connect", recording):
            try:
                a = threading.Thread(target=job, args=("first", first), name="first", daemon=True)
                threads.append(a)
                a.start()
                self.box["first_paused"] = self.entered.wait(WAIT)
                if not self.box["first_paused"]:
                    return self.box
                b = threading.Thread(target=job, args=("second", second), name="second", daemon=True)
                threads.append(b)
                b.start()
                deadline, seen = time.monotonic() + WAIT, {"blocked": False, "waits": []}
                while time.monotonic() < deadline and b.is_alive():
                    seen = self.blocked_by("second", "first")
                    if seen["blocked"]:
                        break
                    time.sleep(0.05)
                self.box["second_blocked_by_first"] = seen["blocked"]
                self.box["second_waits"] = seen["waits"]
                self.box["second_done_while_first_held"] = not b.is_alive()
            finally:
                # always release and join (bounded), so no paused transaction outlives the check
                self.release.set()
                for thread in threads:
                    thread.join(WAIT)
                self.box["joined"] = all(not t.is_alive() for t in threads)
                self.box["pids"] = {k: list(v) for k, v in self.pids.items()}
        return self.box


@unittest.skipUnless(_opt_in(), "Real PostgreSQL E-3 race checks NOT RUN (opt-in not set)")
class RaceTests(RealCase):
    def setup_cards(self, sc):
        sc.clock = cmp.T0
        self.user = sc.user("race")
        sc.set_mode(self.user, "fsrs")
        deck = sc.client.post("/decks", headers=sc.headers(self.user), json={"name": "race-deck"})
        self.deck = int(deck.json()["id"])
        body = {"surface": "r1", "base_form": "r1", "reading": "r", "meaning_ko": "m", "status": "unknown",
                "deck_id": self.deck}
        self.card = int(sc.client.post("/vocab-items", headers=sc.headers(self.user), json=body).json()["id"])
        sc.labels.put("personal", self.card, "r1", owner="race")
        sc.clock = cmp.T0 + timedelta(hours=1)
        self.assertEqual(sc.review(self.user, self.card, "good")["status"], 200)
        sc.clock = cmp.T0 + timedelta(days=2)

    def review_job(self, sc):
        from app.repositories import vocab_repository

        version = sc.version(self.card)
        return lambda: vocab_repository.record_review(self.user, self.card, "good", request_id="race-r2",
                                                      expected_card_version=version, session_id="race")

    def logs(self):
        return self.sql("SELECT count(*) AS n FROM review_logs WHERE vocab_item_id = ?", (self.card,))[0]["n"]

    def check_outcome(self, box, order, kind):
        judge_delete_review(box, order, kind)
        self.assertEqual(self.logs(), 1 if order == "delete first" else 2)  # every committed log kept
        receipts = self.sql("SELECT count(*) AS n FROM srs_review_receipts WHERE card_kind = 'personal' AND card_ref = ?",
                            (self.card,))[0]["n"]
        self.assertEqual(receipts, 1 if order == "delete first" else 2)
        ledger = self.sql("SELECT count(*) AS n FROM srs_card_deletions WHERE card_ref = ?", (self.card,))[0]["n"]
        self.assertEqual(ledger, 1)
        self.assertEqual(self.sql("SELECT count(*) AS n FROM vocab_items WHERE id = ?", (self.card,))[0]["n"], 0)

    def test_word_and_deck_delete_against_review_both_orders(self):
        from app.repositories import deck_repository, vocab_repository
        from app.srs import storage

        self.create()
        for kind in ("word", "deck"):
            for order in ("delete first", "review first"):
                with self.subTest(kind=kind, order=order):
                    self.run.reset(restart_identity=True)
                    with cmp.Scenario("postgresql", self.run) as sc:
                        self.setup_cards(sc)
                        delete = (lambda: vocab_repository.delete_vocab_item(self.user, self.card)) if kind == "word" \
                            else (lambda: deck_repository.delete_deck_with_items(self.user, self.deck))
                        review = self.review_job(sc)
                        jobs = (delete, review) if order == "delete first" else (review, delete)
                        box = Overlap(self, storage, "begin_card_write").run(*jobs)
                    self.check_outcome(box, order, kind)

    def test_upgrade_ddl_against_app_review_write_both_orders(self):
        import app.database as database
        from app.srs import reviews

        # The upgrade runs as in production: the app's own init_db on an ordinary app
        # connection (one transaction). The managed schema step is not used here: it refuses
        # every other app connection in this process while it runs, which would turn the
        # race into a refusal (seen on the first rerun, 2026-10-18).

        for order in ("review first", "upgrade first"):
            with self.subTest(order=order):
                if order == "upgrade first":
                    self.run.reset(restart_identity=True)
                    self.ddl("ALTER TABLE review_logs ADD CONSTRAINT review_logs_vocab_item_id_fkey FOREIGN KEY "
                             "(vocab_item_id) REFERENCES vocab_items(id) ON DELETE CASCADE")  # back to the old shape
                else:
                    self.create(old=True)
                with cmp.Scenario("postgresql", self.run) as sc:
                    self.setup_cards(sc)
                    review = self.review_job(sc)
                    if order == "review first":
                        # paused after its log INSERT (introduced_on runs right after it)
                        box = Overlap(self, reviews, "introduced_on").run(review, database.init_db)
                    else:
                        # paused under the upgrade's table locks: its 2nd catalog read is the re-check
                        box = Overlap(self, database, "_personal_log_card_fks", on_call=2).run(database.init_db, review)
                judge_overlap(box)
                upgrade, review = (box["second"], box["first"]) if order == "review first" else (box["first"], box["second"])
                self.assertEqual(upgrade, ("ok", None), box)                       # init_db returns None
                self.assertEqual(review[0], "ok", box)
                self.assertTrue(isinstance(review[1], dict) and review[1].get("card_id") == self.card, box)
                self.assertEqual(self.card_fks(), [])
                self.assertEqual(self.logs(), 2)

    def test_negative_control_wait_on_another_session_is_not_proof(self):
        """The second job waits -- but on a third session, not on the first. The proof
        must say "not blocked by the first", so judge_overlap() would fail."""
        from app.database import get_connection

        self.create()
        blocker = get_connection()
        try:
            blocker.execute("LOCK TABLE lexemes IN ACCESS EXCLUSIVE MODE")  # an owned table of this run

            def first():
                with get_connection() as c:
                    c.execute("SELECT 1 FROM users LIMIT 1").fetchall()
                    pg_checkpoint()  # paused here, holding only its own harmless read

            def second():
                with get_connection() as c:
                    return c.execute("SELECT count(*) AS n FROM lexemes").fetchone()["n"]

            overlap = Overlap(self, sys.modules[__name__], "pg_checkpoint")
            box_holder = {}

            def release_blocker_later():
                # the second must be seen waiting on the blocker first, then the blocker goes
                deadline = time.monotonic() + WAIT
                while time.monotonic() < deadline:
                    if overlap.blocked_by("second", "first")["waits"]:
                        box_holder["seen_waiting_on_blocker"] = True
                        break
                    time.sleep(0.05)

            watcher = threading.Thread(target=release_blocker_later, daemon=True)
            # Run with a short proof window: the second never waits for the first.
            with mock.patch(f"{__name__}.WAIT", 3.0):
                watcher.start()
                box = overlap.run(first, second)
            watcher.join(WAIT)
        finally:
            blocker.close()
            deadline = time.monotonic() + WAIT  # the released second finishes; nothing stays open
            while "second" not in overlap.box and time.monotonic() < deadline:
                time.sleep(0.05)
        self.assertTrue(box_holder.get("seen_waiting_on_blocker"), box)
        self.assertFalse(box["second_blocked_by_first"], box)
        with self.assertRaises(AssertionError):
            judge_overlap(box)


